const { contextBridge, ipcRenderer } = require('electron');
const invoke = (name, ...args) => ipcRenderer.invoke(name, ...args);
contextBridge.exposeInMainWorld('recorderApp', {
  platform: process.platform,
  microphoneAccess: enabled => invoke('microphone-access',enabled),
  capabilities: () => invoke('capabilities'),
  captureReady: () => invoke('capture-ready'),
  audioAck: bytes => invoke('audio-ack',bytes),
  onProcessingError: listener => ipcRenderer.on('processing-error',(_event,error)=>listener(error)),
  applicationAudio: () => invoke('application-audio'),
  rotate: duration => invoke('rotate',duration),
  history: () => invoke('history'),
  historyOpen: (id,index,action) => invoke('history-open',id,index,action),
  repair: (id,index) => invoke('repair',id,index),
  onHistory: listener => ipcRenderer.on('history',()=>listener()),
  onProcessing: listener => ipcRenderer.on('processing',(_event,data)=>listener(data)),
  onLowDisk: listener => ipcRenderer.on('low-disk',(_event,data)=>listener(data)),
  onDisk: listener => ipcRenderer.on('disk',(_event,data)=>listener(data)),
  onDiskWarning: listener => ipcRenderer.on('disk-warning',()=>listener()),
  onWindowState: listener => ipcRenderer.on('window-state',(_event,state)=>listener(state)),
  onApplicationAudio: listener => ipcRenderer.on('application-audio-data',(_event,data)=>listener(data)),
  onAudioEnded: listener => ipcRenderer.on('audio-ended',()=>listener()),
  onScheduleStart: listener => ipcRenderer.on('schedule-start',()=>listener()),
  onScheduleStop: listener => ipcRenderer.on('schedule-stop',()=>listener()),
  openWebinar: url => invoke('open-webinar', url),
  sources: mode => invoke('sources', mode),
  prepare: options => invoke('prepare', options),
  write: data => invoke('write', data),
  finish: duration => invoke('finish',duration),
  abort: () => invoke('abort'),
  showFile: () => invoke('show-file'),
  revealWebinar: () => invoke('reveal-webinar'),
  toggleWebinarFullscreen: () => invoke('toggle-webinar-fullscreen'),
  updateState: () => invoke('update-state'),
  checkUpdates: () => invoke('check-updates'),
  installUpdate: () => invoke('install-update'),
  onUpdate: listener => ipcRenderer.on('update-state', (_event, state) => listener(state)),
  onNotice: listener => ipcRenderer.on('notice', (_event, message) => listener(message)),
  onSourceEnded: listener => ipcRenderer.on('source-ended', () => listener())
});
